-- 1KYCore campaign template inventory, 2026-10-01.
-- Read-only: run against the world database after its normal updates.
-- Missing live spawns may be zero because invalid imported spawns were removed.
SELECT g.id AS missing_template_entry, COUNT(*) AS invalid_live_spawns
FROM gameobject g LEFT JOIN gameobject_template t ON t.entry=g.id
WHERE t.entry IS NULL GROUP BY g.id ORDER BY g.id;

